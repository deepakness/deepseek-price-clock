/* DeepSeek peak/off-peak price logic, ported from ../../price.js.
   Keep SWITCH_MINUTES, weekendRuleStart and cnHolidays in sync with it; the
   fixtures under Tests/ are generated by running the JavaScript itself. */

import Foundation

public enum Phase: String, Codable, Sendable {
  case peak
  case off
}

public struct Switch: Sendable, Equatable {
  public let date: Date
  public let phase: Phase
}

/// The window you are in, plus where it ends and how far into the UTC day you
/// are (the popup uses that for the timeline marker).
public struct CurrentWindow: Sendable, Equatable {
  public let phase: Phase
  public let nextPhase: Phase
  public let end: Date
  public let minuteOfDay: Int
}

/// One stretch of the 24-hour bar, in display-time minutes from local midnight.
public struct DaySegment: Sendable, Equatable {
  public let startMinute: Double
  public let endMinute: Double
  public let phase: Phase
}

public struct PriceWindow: Sendable, Equatable {
  public let start: Date
  public let end: Date
  public let phase: Phase
  public let isCurrent: Bool
}

public enum PriceClock {
  /// Peak window switch instants in UTC minutes-of-day. Chinese standard time
  /// is a fixed +08:00, so Beijing arithmetic is a shift on the instant rather
  /// than a calendar lookup.
  public static let switchMinutes = [60, 240, 360, 600]

  /// Since 00:00 Beijing time on Sunday August 23, 2026 the split only applies
  /// Monday to Friday Beijing time.
  public static let weekendRuleStart = Date(timeIntervalSince1970: 1_787_414_400)

  /// Chinese public holidays from the State Council's yearly arrangement, as
  /// Beijing date keys. DeepSeek bills them off-peak all day.
  public static let cnHolidays: [(from: String, to: String)] = [
    ("2026-09-25", "2026-09-27"), // Mid-Autumn
    ("2026-10-01", "2026-10-07"), // National Day
  ]

  static let beijingOffset: TimeInterval = 8 * 3600

  static func beijingWeekday(_ date: Date) -> Int {
    // Day 0 of the epoch (1970-01-01) was a Thursday.
    let days = Int(((date.timeIntervalSince1970 + beijingOffset) / 86400).rounded(.down))
    return ((days % 7) + 11) % 7  // 0 = Sunday
  }

  static func beijingDateKey(_ date: Date) -> String {
    let shifted = date.timeIntervalSince1970 + beijingOffset
    let dayStart = (shifted / 86400).rounded(.down) * 86400
    var calendar = Calendar(identifier: .gregorian)
    calendar.timeZone = TimeZone(identifier: "UTC")!
    let parts = calendar.dateComponents(
      [.year, .month, .day], from: Date(timeIntervalSince1970: dayStart))
    return String(format: "%04d-%02d-%02d", parts.year!, parts.month!, parts.day!)
  }

  static func isBeijingWeekend(_ date: Date) -> Bool {
    let weekday = beijingWeekday(date)
    return weekday == 0 || weekday == 6
  }

  static func isBeijingHoliday(_ date: Date) -> Bool {
    let key = beijingDateKey(date)
    for holiday in cnHolidays where key >= holiday.from && key <= holiday.to {
      return true
    }
    return false
  }

  /// A Saturday, Sunday or public holiday under the new rules is off-peak all
  /// day.
  public static func offPeakAllDay(_ date: Date) -> Bool {
    guard date >= weekendRuleStart else { return false }
    return isBeijingWeekend(date) || isBeijingHoliday(date)
  }

  static func minuteOfDay(_ date: Date) -> Int {
    let minutes = Int((date.timeIntervalSince1970 / 60).rounded(.down))
    return ((minutes % 1440) + 1440) % 1440
  }

  /// Which half of the pricing an instant falls in.
  public static func phase(at date: Date) -> Phase {
    if offPeakAllDay(date) { return .off }
    let minute = minuteOfDay(date)
    return (minute >= 60 && minute < 240) || (minute >= 360 && minute < 600) ? .peak : .off
  }

  /// A switch minute is a real price change only outside gated
  /// weekends/holidays.
  public static func isSwitchInstant(_ date: Date) -> Bool {
    let minute = minuteOfDay(date)
    guard switchMinutes.contains(minute) else { return false }
    return !offPeakAllDay(date)
  }

  static func utcDayStart(_ date: Date) -> Date {
    Date(timeIntervalSince1970: (date.timeIntervalSince1970 / 86400).rounded(.down) * 86400)
  }

  /// The next `count` price changes as absolute instants. Candidates are walked
  /// day by day from UTC midnight, so a long holiday stretch simply skips.
  public static func nextSwitches(after date: Date, count: Int) -> [Switch] {
    let dayStart = utcDayStart(date).timeIntervalSince1970
    var out: [Switch] = []
    var day = 0
    var index = 0
    while out.count < count {
      let seconds = dayStart + Double(day) * 86400 + Double(switchMinutes[index]) * 60
      if seconds > date.timeIntervalSince1970 {
        let candidate = Date(timeIntervalSince1970: seconds)
        if isSwitchInstant(candidate) {
          out.append(Switch(date: candidate, phase: phase(at: candidate)))
        }
      }
      index += 1
      if index >= switchMinutes.count {
        index = 0
        day += 1
      }
    }
    return out
  }

  public static func currentWindow(at date: Date) -> CurrentWindow {
    let next = nextSwitches(after: date, count: 1)[0]
    return CurrentWindow(
      phase: phase(at: date),
      nextPhase: next.phase,
      end: next.date,
      minuteOfDay: minuteOfDay(date)
    )
  }

  /// The instant the window you are in began. Walks back up to 21 days to cross
  /// any weekend + holiday off-peak stretch.
  public static func currentWindowStart(at date: Date) -> Date {
    let dayStart = utcDayStart(date).timeIntervalSince1970
    var best: Date?
    for day in -21...0 {
      for minute in switchMinutes {
        let seconds = dayStart + Double(day) * 86400 + Double(minute) * 60
        guard seconds <= date.timeIntervalSince1970 else { continue }
        let candidate = Date(timeIntervalSince1970: seconds)
        guard isSwitchInstant(candidate) else { continue }
        if best == nil || seconds > best!.timeIntervalSince1970 {
          best = candidate
        }
      }
    }
    return best ?? date.addingTimeInterval(-86400)
  }

  /// Rebuild the 24-hour day bar in display time (`offsetMinutes` ahead of UTC).
  /// price.js derives the day start from the host's local date; with
  /// `shifted = date + offset` the closed form below is the same instant, which
  /// is what keeps the fixtures machine-independent.
  public static func displaySegments(at date: Date, offsetMinutes: Int) -> [DaySegment] {
    let offset = Double(offsetMinutes) * 60
    let shifted = date.timeIntervalSince1970 + offset
    let dayStart = (shifted / 86400).rounded(.down) * 86400 - offset

    func normalised(_ minutes: Int) -> Double {
      let wrapped = Double(minutes % 1440)
      return wrapped < 0 ? wrapped + 1440 : wrapped
    }

    var boundaries: [Double] = [0, 1440]
    for minute in switchMinutes {
      boundaries.append(normalised(minute + offsetMinutes))
    }
    // 16:00 UTC is a boundary the popup bar draws but not a price switch.
    boundaries.append(normalised(960 + offsetMinutes))
    boundaries.sort()

    var raw: [(start: Double, end: Double, phase: Phase)] = []
    for index in 0..<(boundaries.count - 1) {
      let start = boundaries[index]
      let end = boundaries[index + 1]
      guard end > start else { continue }
      let sample = Date(timeIntervalSince1970: dayStart + (start + 0.5) * 60)
      raw.append((start, end, phase(at: sample)))
    }

    var merged: [DaySegment] = []
    for segment in raw {
      if let last = merged.last, last.phase == segment.phase {
        merged[merged.count - 1] = DaySegment(
          startMinute: last.startMinute, endMinute: segment.end, phase: segment.phase)
      } else {
        merged.append(
          DaySegment(startMinute: segment.start, endMinute: segment.end, phase: segment.phase))
      }
    }
    return merged
  }

  /// Windows as start/end pairs, opening with the active window.
  public static func windows(at date: Date, count: Int) -> [PriceWindow] {
    let upcoming = nextSwitches(after: date, count: count)
    var start = currentWindowStart(at: date)
    var phase = phase(at: date)
    var out: [PriceWindow] = []
    for index in 0..<count {
      out.append(
        PriceWindow(start: start, end: upcoming[index].date, phase: phase, isCurrent: index == 0))
      start = upcoming[index].date
      phase = upcoming[index].phase
    }
    return out
  }
}
